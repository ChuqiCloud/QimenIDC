package com.chuqiyun.proxmoxveams.security;

import com.baomidou.mybatisplus.core.MybatisConfiguration;
import com.baomidou.mybatisplus.extension.spring.MybatisSqlSessionFactoryBean;
import com.chuqiyun.proxmoxveams.dao.TaskDao;
import com.chuqiyun.proxmoxveams.entity.Task;
import org.apache.ibatis.session.SqlSession;
import org.junit.jupiter.api.AfterEach;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.Test;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.jdbc.datasource.DriverManagerDataSource;

import java.util.LinkedHashMap;
import java.util.Map;
import java.util.UUID;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertNotEquals;
import static org.junit.jupiter.api.Assertions.assertTrue;

class EncryptedTaskParamsPersistenceTest {
    private SqlSession session;
    private JdbcTemplate jdbc;

    @BeforeEach
    void openDatabase() throws Exception {
        DriverManagerDataSource dataSource = new DriverManagerDataSource(
                "jdbc:h2:mem:task_params_" + UUID.randomUUID() + ";MODE=MySQL;DB_CLOSE_DELAY=-1", "sa", "");
        MybatisConfiguration configuration = new MybatisConfiguration();
        configuration.setMapUnderscoreToCamelCase(true);
        configuration.addMapper(TaskDao.class);
        MybatisSqlSessionFactoryBean factoryBean = new MybatisSqlSessionFactoryBean();
        factoryBean.setDataSource(dataSource);
        factoryBean.setConfiguration(configuration);
        session = factoryBean.getObject().openSession(true);
        jdbc = new JdbcTemplate(dataSource);
        jdbc.execute("create table task (id int generated by default as identity primary key, "
                + "nodeid int, vmid int, hostid int, type int, status int, params varchar(8192), "
                + "error varchar(8192), create_date bigint)");
    }

    @AfterEach
    void closeDatabase() {
        if (session != null) {
            session.close();
        }
    }

    @Test
    void taskParamsRoundTripUsesJsonCiphertextAndReturnsPlaintext() {
        TaskDao mapper = session.getMapper(TaskDao.class);
        Map<Object, Object> params = new LinkedHashMap<>();
        params.put("stage", "running");
        params.put("progress", 40);
        params.put("newPassword", "task-secret");

        Task task = new Task();
        task.setStatus(1);
        task.setParams(params);
        assertEquals(1, mapper.insert(task));

        String first = jdbc.queryForObject("select params from task where id = ?", String.class, task.getId());
        assertTrue(first.startsWith("{"));
        assertTrue(first.contains("QIDENC:1:"));
        assertTrue(!first.contains("task-secret"));

        Task loaded = mapper.selectById(task.getId());
        assertEquals("running", loaded.getParams().get("stage"));
        assertEquals(40, ((Number) loaded.getParams().get("progress")).intValue());
        assertEquals("task-secret", loaded.getParams().get("newPassword"));

        loaded.getParams().put("progress", 80);
        assertEquals(1, mapper.updateById(loaded));
        String second = jdbc.queryForObject("select params from task where id = ?", String.class, task.getId());
        assertNotEquals(first, second);
        assertTrue(second.contains("QIDENC:1:"));
        assertTrue(!second.contains("task-secret"));
        assertEquals(80, ((Number) mapper.selectById(task.getId()).getParams().get("progress")).intValue());
    }
}
