package com.chuqiyun.proxmoxveams.service.impl;

import com.baomidou.mybatisplus.core.MybatisConfiguration;
import com.baomidou.mybatisplus.extension.spring.MybatisSqlSessionFactoryBean;
import com.chuqiyun.proxmoxveams.dao.SysuserDao;
import com.chuqiyun.proxmoxveams.entity.Sysuser;
import com.chuqiyun.proxmoxveams.utils.EncryptUtil;
import org.apache.ibatis.session.SqlSession;
import org.junit.jupiter.api.AfterEach;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.Test;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.jdbc.datasource.DriverManagerDataSource;
import org.springframework.test.util.ReflectionTestUtils;

import java.util.UUID;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertFalse;
import static org.junit.jupiter.api.Assertions.assertNull;
import static org.junit.jupiter.api.Assertions.assertTrue;

/**
 * @Author: 星禾
 * @Description: TOTP lifecycle and session revocation persistence regressions
 * @DateTime: 2026/10/17 16:01
 */
class SysuserSecurityPersistenceTest {
    private SqlSession session;
    private SysuserServiceImpl service;
    private SysuserDao mapper;
    private Integer userId;

    @BeforeEach
    void openDatabase() throws Exception {
        DriverManagerDataSource dataSource = new DriverManagerDataSource(
                "jdbc:h2:mem:sysuser_security_" + UUID.randomUUID() + ";MODE=MySQL;DB_CLOSE_DELAY=-1", "sa", "");
        new JdbcTemplate(dataSource).execute("create table sysuser (id int generated by default as identity primary key, "
                + "uuid varchar(64), username varchar(100), password varchar(255), name varchar(100), phone varchar(30), "
                + "email varchar(100), logindate varchar(255), mfa_type varchar(16), totp_secret text, "
                + "totp_confirmed_time bigint, totp_last_step bigint, passkey_enabled int)");
        MybatisConfiguration configuration = new MybatisConfiguration();
        configuration.setMapUnderscoreToCamelCase(true);
        configuration.addMapper(SysuserDao.class);
        MybatisSqlSessionFactoryBean factory = new MybatisSqlSessionFactoryBean();
        factory.setDataSource(dataSource);
        factory.setConfiguration(configuration);
        session = factory.getObject().openSession(true);
        mapper = session.getMapper(SysuserDao.class);
        service = new SysuserServiceImpl();
        ReflectionTestUtils.setField(service, "baseMapper", mapper);
        Sysuser user = new Sysuser();
        user.setUsername("admin");
        user.setUuid("test-user");
        user.setPassword(EncryptUtil.md5("old-password"));
        user.setMfaType("none");
        mapper.insert(user);
        userId = user.getId();
    }

    @AfterEach
    void closeDatabase() {
        if (session != null) {
            session.close();
        }
    }

    @Test
    void confirmationConsumesStepAtomicallyAndSettingsCannotOverwriteIt() {
        assertTrue(service.startTotpBinding(userId, "encrypted-secret"));
        Sysuser stale = mapper.selectById(userId);

        assertFalse(service.confirmTotpBinding(userId, "another-secret", 100));
        assertTrue(service.confirmTotpBinding(userId, "encrypted-secret", 100));
        assertFalse(service.confirmTotpBinding(userId, "encrypted-secret", 100));
        stale.setMfaType("totp");
        assertTrue(service.updateMfaSettings(stale));

        Sysuser confirmed = mapper.selectById(userId);
        assertEquals(100L, confirmed.getTotpLastStep());
        assertTrue(confirmed.getTotpConfirmedTime() > 0);
        assertFalse(service.consumeTotpStep(userId, 100));
        assertFalse(service.startTotpBinding(userId, "replacement-secret"));
        assertEquals("encrypted-secret", mapper.selectById(userId).getTotpSecret());
    }

    @Test
    void unbindingClearsActivePolicyAndAllowsNewSecret() {
        service.startTotpBinding(userId, "encrypted-secret");
        service.confirmTotpBinding(userId, "encrypted-secret", 100);
        Sysuser user = mapper.selectById(userId);
        user.setMfaType("totp");
        service.updateMfaSettings(user);

        assertTrue(service.clearTotpBinding(userId));

        Sysuser cleared = mapper.selectById(userId);
        assertEquals("none", cleared.getMfaType());
        assertNull(cleared.getTotpSecret());
        assertNull(cleared.getTotpConfirmedTime());
        assertNull(cleared.getTotpLastStep());
        assertTrue(service.startTotpBinding(userId, "new-secret"));
    }

    @Test
    void loginAndPasswordResetAlwaysAdvanceExistingSessionEvenInSameMillisecond() {
        long futureMarker = System.currentTimeMillis() + 60_000;
        Sysuser user = mapper.selectById(userId);
        user.setLogindate(futureMarker);
        mapper.updateById(user);

        assertEquals(futureMarker + 1, service.rotateLoginSession(userId));
        assertNull(service.resetOwnPassword(userId, "old-password", "new-password"));
        assertEquals(futureMarker + 2, mapper.selectById(userId).getLogindate());
        assertEquals(futureMarker + 3, service.rotateLoginSession(userId));
        assertFalse(service.verifyPassword(userId, "old-password"));
        assertTrue(service.verifyPassword(userId, "new-password"));
    }

    @Test
    void staleProfileUpdatesCannotRestoreConsumedStepsSecretsOrSessions() {
        assertTrue(service.startTotpBinding(userId, "encrypted-secret"));
        Sysuser stale = mapper.selectById(userId);
        assertTrue(service.confirmTotpBinding(userId, "encrypted-secret", 100));
        Long activeSession = service.rotateLoginSession(userId);
        stale.setName("Updated name");

        assertTrue(service.updateAccountDetails(stale, null));

        Sysuser saved = mapper.selectById(userId);
        assertEquals("Updated name", saved.getName());
        assertEquals(activeSession, saved.getLogindate());
        assertEquals(100L, saved.getTotpLastStep());
        assertTrue(saved.getTotpConfirmedTime() > 0);
        assertFalse(service.consumeTotpStep(userId, 100));
    }

    @Test
    void administratorPasswordResetAlsoRotatesTargetAccountSession() {
        long futureMarker = System.currentTimeMillis() + 60_000;
        Sysuser current = mapper.selectById(userId);
        current.setLogindate(futureMarker);
        mapper.updateById(current);
        Sysuser updates = new Sysuser();
        updates.setId(userId);
        updates.setEmail("updated@example.com");

        assertTrue(service.updateAccountDetails(updates, EncryptUtil.md5("admin-reset-password")));

        Sysuser saved = mapper.selectById(userId);
        assertEquals(futureMarker + 1, saved.getLogindate());
        assertEquals("updated@example.com", saved.getEmail());
        assertEquals("admin", saved.getUsername());
        assertTrue(service.verifyPassword(userId, "admin-reset-password"));
        assertFalse(service.verifyPassword(userId, "old-password"));
    }
}
