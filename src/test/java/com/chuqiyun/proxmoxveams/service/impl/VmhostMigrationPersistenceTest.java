package com.chuqiyun.proxmoxveams.service.impl;

import com.baomidou.mybatisplus.core.MybatisConfiguration;
import com.baomidou.mybatisplus.core.conditions.update.UpdateWrapper;
import com.baomidou.mybatisplus.core.metadata.TableInfo;
import com.baomidou.mybatisplus.core.metadata.TableInfoHelper;
import com.baomidou.mybatisplus.extension.spring.MybatisSqlSessionFactoryBean;
import com.chuqiyun.proxmoxveams.dao.VmhostDao;
import com.chuqiyun.proxmoxveams.entity.Vmhost;
import org.apache.ibatis.session.SqlSession;
import org.junit.jupiter.api.Test;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.jdbc.datasource.DriverManagerDataSource;
import org.springframework.test.util.ReflectionTestUtils;

import java.util.LinkedHashMap;
import java.util.Map;
import java.util.UUID;
import java.util.stream.Collectors;

import static org.junit.jupiter.api.Assertions.*;

class VmhostMigrationPersistenceTest {
    @Test
    void staleBackgroundEntityCannotRestoreSourceLocationOrNetworkAfterMigration() throws Exception {
        DriverManagerDataSource source = new DriverManagerDataSource("jdbc:h2:mem:" + UUID.randomUUID()
                + ";MODE=MySQL;DB_CLOSE_DELAY=-1", "sa", "");
        MybatisConfiguration configuration = new MybatisConfiguration();
        configuration.setMapUnderscoreToCamelCase(true);
        configuration.addMapper(VmhostDao.class);
        MybatisSqlSessionFactoryBean factory = new MybatisSqlSessionFactoryBean();
        factory.setDataSource(source);
        factory.setConfiguration(configuration);
        try (SqlSession session = factory.getObject().openSession(true)) {
            JdbcTemplate jdbc = new JdbcTemplate(source);
            TableInfo table = TableInfoHelper.getTableInfo(Vmhost.class);
            String columns = table.getFieldList().stream()
                    .map(field -> "`" + field.getColumn() + "` varchar(8192)")
                    .collect(Collectors.joining(", "));
            jdbc.execute("create table vmhost(id int generated by default as identity primary key, " + columns + ")");
            VmhostDao mapper = session.getMapper(VmhostDao.class);
            VmhostServiceImpl service = new VmhostServiceImpl();
            ReflectionTestUtils.setField(service, "baseMapper", mapper);
            Vmhost vm = new Vmhost();
            vm.setNodeid(1);
            vm.setVmid(101);
            vm.setStatus(1);
            vm.setIpConfig(new LinkedHashMap<>(Map.of("1", "ip=172.16.0.4/24,gw=172.16.0.1")));
            vm.setPassword("vm-password");
            mapper.insert(vm);
            Vmhost stale = mapper.selectById(vm.getId());
            Map<String, String> targetNetwork = new LinkedHashMap<>(Map.of("1", "ip=172.17.0.8/24,gw=172.17.0.1"));
            Vmhost move = new Vmhost();
            move.setNodeid(2);
            move.setVmid(201);
            move.setIpConfig(targetNetwork);
            assertEquals(1, mapper.update(move, new UpdateWrapper<Vmhost>()
                    .eq("id", vm.getId()).eq("nodeid", 1).eq("vmid", 101)));

            stale.setStatus(0);
            stale.setUsedFlow(999D);
            assertFalse(service.updateById(stale));
            Vmhost current = mapper.selectById(vm.getId());
            assertEquals(2, current.getNodeid());
            assertEquals(201, current.getVmid());
            assertEquals(targetNetwork, current.getIpConfig());
            assertEquals(1, current.getStatus());
            assertNull(current.getUsedFlow());

            current.setStatus(0);
            assertTrue(service.updateById(current));
            Vmhost partial = new Vmhost();
            partial.setId(vm.getId());
            partial.setBandwidth(100);
            assertTrue(service.updateById(partial));
            Vmhost updated = mapper.selectById(vm.getId());
            assertEquals(0, updated.getStatus());
            assertEquals(100, updated.getBandwidth());
            assertEquals(targetNetwork, updated.getIpConfig());
            assertEquals("vm-password", updated.getPassword());
        }
    }
}
