/**
 * @Author: 星禾
 * @Description: 验证 Passkey 注册与管理员重置通过账号行锁串行化，旧挑战无法恢复被删除凭据
 * @DateTime: 2026/11/19 18:30
 */
class PasskeyRegistrationResetTest {
    private static final String RP_ID = "idc.example.com";
    private JdbcTemplate jdbc;
    private DataSourceTransactionManager transactions;
    private SysPasskeyService credentials;
    private PasskeyService registration;
    private SysuserMfaService resets;
    private Sysuser user;

    @BeforeEach
    void setup() {
        DriverManagerDataSource source = new DriverManagerDataSource("jdbc:h2:mem:passkey_registration_reset_"
                + UUID.randomUUID() + ";MODE=MySQL;DB_CLOSE_DELAY=-1;LOCK_TIMEOUT=5000", "sa", "");
        jdbc = new JdbcTemplate(source);
        transactions = new DataSourceTransactionManager(source);
        jdbc.execute("create table sysuser (id int primary key, uuid varchar(255), logindate varchar(255), "
                + "mfa_type varchar(16), passkey_enabled int)");
        jdbc.execute("create table sys_passkey (id bigint generated by default as identity primary key, userid int)");
        jdbc.execute("create table sys_passkey_challenge (challenge varchar(64) primary key, type varchar(24), "
                + "user_uuid varchar(64), expires_at bigint)");
        jdbc.update("insert into sysuser values (1, 'registration-user', 123, 'none', 0)");
        user = new Sysuser();
        user.setId(1);
        user.setUuid("registration-user");
        user.setUsername("admin");
        credentials = mock(SysPasskeyService.class);
        when(credentials.listByUserId(1)).thenReturn(List.of());
        PasskeyServiceImpl implementation = new PasskeyServiceImpl();
        ReflectionTestUtils.setField(implementation, "jdbc", jdbc);
        ReflectionTestUtils.setField(implementation, "sysPasskeyService", credentials);
        ReflectionTestUtils.setField(implementation, "rpId", RP_ID);
        ReflectionTestUtils.setField(implementation, "rpName", "QimenIDC");
        ReflectionTestUtils.setField(implementation, "origin", "https://" + RP_ID);
        ReflectionTestUtils.setField(implementation, "requireUserVerification", false);
        registration = (PasskeyService) transactionalProxy(implementation);
        resets = (SysuserMfaService) transactionalProxy(new SysuserMfaService(jdbc));
    }

    @Test
    void resetWaitsForRegistrationThenRemovesItsNewCredential() throws Exception {
        JSONObject response = responseForNewChallenge();
        CountDownLatch atSave = new CountDownLatch(1);
        CountDownLatch allowSave = new CountDownLatch(1);
        CountDownLatch resetStarted = new CountDownLatch(1);
        when(credentials.save(any(SysPasskey.class))).thenAnswer(call -> {
            atSave.countDown();
            assertTrue(allowSave.await(5, TimeUnit.SECONDS));
            jdbc.update("insert into sys_passkey (userid) values (1)");
            return true;
        });
        ExecutorService executor = Executors.newFixedThreadPool(2);
        try {
            var registered = executor.submit(() -> registration.finishRegistration(user, response, "Browser"));
            assertTrue(atSave.await(5, TimeUnit.SECONDS));
            var reset = executor.submit(() -> {
                resetStarted.countDown();
                return resets.resetPasskey(1);
            });
            assertTrue(resetStarted.await(5, TimeUnit.SECONDS));
            assertThrows(TimeoutException.class, () -> reset.get(150, TimeUnit.MILLISECONDS));
            allowSave.countDown();
            registered.get(5, TimeUnit.SECONDS);
            assertTrue(reset.get(5, TimeUnit.SECONDS));

            assertEquals(0, jdbc.queryForObject("select count(*) from sys_passkey", Integer.class));
            assertEquals(0, jdbc.queryForObject("select passkey_enabled from sysuser where id = 1", Integer.class));
            assertEquals(0, jdbc.queryForObject("select count(*) from sys_passkey_challenge", Integer.class));
        } finally {
            allowSave.countDown();
            executor.shutdownNow();
            assertTrue(executor.awaitTermination(5, TimeUnit.SECONDS));
        }
    }

    @Test
    void resetBeforeRegistrationRevokesItsOutstandingChallenge() throws Exception {
        JSONObject response = responseForNewChallenge();
        assertTrue(resets.resetPasskey(1));

        AuthException error = assertThrows(AuthException.class,
                () -> registration.finishRegistration(user, response, "Browser"));

        assertEquals(ResponseResult.RespCode.PASSKEY_CHALLENGE_EXPIRED, error.getRespCode());
        verify(credentials, never()).save(any(SysPasskey.class));
        assertEquals(0, jdbc.queryForObject("select count(*) from sys_passkey", Integer.class));
        assertEquals(0, jdbc.queryForObject("select passkey_enabled from sysuser where id = 1", Integer.class));
    }

    @Test
    void failedCredentialWriteRollsBackConsumedChallenge() throws Exception {
        JSONObject response = responseForNewChallenge();
        when(credentials.save(any(SysPasskey.class))).thenReturn(false);

        assertThrows(AuthException.class, () -> registration.finishRegistration(user, response, "Browser"));

        assertEquals(1, jdbc.queryForObject("select count(*) from sys_passkey_challenge", Integer.class));
        assertEquals(0, jdbc.queryForObject("select passkey_enabled from sysuser where id = 1", Integer.class));
    }

    private Object transactionalProxy(Object implementation) {
        ProxyFactory proxy = new ProxyFactory(implementation);
        proxy.addAdvice(new TransactionInterceptor(transactions, new AnnotationTransactionAttributeSource()));
        return proxy.getProxy();
    }

    private JSONObject responseForNewChallenge() throws Exception {
        String challenge = (String) registration.createRegistrationOptions(user).get("challenge");
        KeyPairGenerator generator = KeyPairGenerator.getInstance("RSA");
        generator.initialize(2048);
        RSAPublicKey key = (RSAPublicKey) generator.generateKeyPair().getPublic();
        byte[] cose = concat(new byte[]{(byte) 0xa4, 1, 3, 3, 0x39, 1, 0, 0x20},
                cborBytes(unsigned(key.getModulus().toByteArray())), new byte[]{0x21},
                cborBytes(unsigned(key.getPublicExponent().toByteArray())));
        byte[] id = new byte[]{1, 2, 3};
        byte[] authData = concat(WebAuthnUtil.sha256(RP_ID.getBytes(StandardCharsets.UTF_8)),
                new byte[]{0x41, 0, 0, 0, 0}, new byte[16], new byte[]{0, (byte) id.length}, id, cose);
        byte[] attestation = concat(new byte[]{(byte) 0xa1, 0x68}, "authData".getBytes(StandardCharsets.UTF_8),
                cborBytes(authData));
        JSONObject clientData = new JSONObject();
        clientData.put("type", "webauthn.create");
        clientData.put("origin", "https://" + RP_ID);
        clientData.put("challenge", challenge);
        JSONObject response = new JSONObject();
        response.put("attestationObject", Base64UrlUtil.encode(attestation));
        response.put("clientDataJSON", Base64UrlUtil.encode(clientData.toJSONString().getBytes(StandardCharsets.UTF_8)));
        JSONObject credential = new JSONObject();
        credential.put("response", response);
        return credential;
    }

    private static byte[] unsigned(byte[] value) {
        return value[0] == 0 ? Arrays.copyOfRange(value, 1, value.length) : value;
    }

    private static byte[] cborBytes(byte[] value) {
        byte[] header = value.length < 24 ? new byte[]{(byte) (0x40 | value.length)}
                : value.length < 256 ? new byte[]{0x58, (byte) value.length}
                : new byte[]{0x59, (byte) (value.length >> 8), (byte) value.length};
        return concat(header, value);
    }

    private static byte[] concat(byte[]... values) {
        ByteArrayOutputStream result = new ByteArrayOutputStream();
        Arrays.stream(values).forEach(result::writeBytes);
        return result.toByteArray();
    }
}
