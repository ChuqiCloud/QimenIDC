package com.chuqiyun.proxmoxveams.service.impl;

import com.baomidou.mybatisplus.core.MybatisConfiguration;
import com.baomidou.mybatisplus.extension.spring.MybatisSqlSessionFactoryBean;
import com.chuqiyun.proxmoxveams.constant.TaskStatus;
import com.chuqiyun.proxmoxveams.dao.TaskDao;
import com.chuqiyun.proxmoxveams.dto.TaskCountDto;
import org.apache.ibatis.session.SqlSession;
import org.junit.jupiter.api.Test;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.jdbc.datasource.DriverManagerDataSource;

import java.util.List;
import java.util.UUID;

import static org.junit.jupiter.api.Assertions.assertEquals;

/**
 * @Author: 星禾
 * @Description: 验证管理端任务分组统计 SQL
 * @DateTime: 2026/10/17 15:52
 */
class TaskServiceAggregateQueryTest {

    @Test
    void statisticsAndRunningSummaryAggregateRowsBySelectedColumn() throws Exception {
        DriverManagerDataSource dataSource = new DriverManagerDataSource(
                "jdbc:h2:mem:task_aggregate_" + UUID.randomUUID()
                        + ";MODE=MySQL;DATABASE_TO_LOWER=TRUE;DB_CLOSE_DELAY=-1", "sa", "");
        MybatisConfiguration configuration = new MybatisConfiguration();
        configuration.addMapper(TaskDao.class);
        MybatisSqlSessionFactoryBean factoryBean = new MybatisSqlSessionFactoryBean();
        factoryBean.setDataSource(dataSource);
        factoryBean.setConfiguration(configuration);
        try (SqlSession session = factoryBean.getObject().openSession(true)) {
            JdbcTemplate jdbc = new JdbcTemplate(dataSource);
            jdbc.execute("create table task (id int generated by default as identity primary key, "
                    + "nodeid int, vmid int, hostid int, type int, status int, params varchar(8192), "
                    + "error varchar(8192), create_date bigint)");
            jdbc.update("insert into task (type, status, create_date) values (40, ?, 1000)", TaskStatus.RUNNING);
            jdbc.update("insert into task (type, status, create_date) values (40, ?, 2000)", TaskStatus.RUNNING);
            jdbc.update("insert into task (type, status, create_date) values (32, ?, 3000)", TaskStatus.FAILURE);
            jdbc.update("insert into task (type, status, create_date) values (32, ?, 4000)", TaskStatus.RUNNING);

            TestableTaskService service = new TestableTaskService();
            service.useMapper(session.getMapper(TaskDao.class));
            List<TaskCountDto> byStatus = service.getTaskStatisticsForAdmin("status", null, null);
            List<TaskCountDto> byType = service.getTaskStatisticsForAdmin("type", null, null);

            assertEquals(2, byStatus.size());
            assertEquals(3L, byStatus.stream().filter(row -> TaskStatus.RUNNING.equals(row.getStatus()))
                    .findFirst().orElseThrow().getCount());
            assertEquals(2, byType.size());
            assertEquals(2L, byType.stream().filter(row -> Integer.valueOf(40).equals(row.getType()))
                    .findFirst().orElseThrow().getCount());
            assertEquals(1L, service.getTaskStatisticsForAdmin("status", 2000L, 3000L).stream()
                    .filter(row -> TaskStatus.RUNNING.equals(row.getStatus())).findFirst().orElseThrow().getCount());
            assertEquals(3L, service.getRunningTaskSummary().get("runningCount"));
            assertEquals(2, ((List<?>) service.getRunningTaskSummary().get("runningByType")).size());
        }
    }

    private static class TestableTaskService extends TaskServiceImpl {
        void useMapper(TaskDao mapper) {
            this.baseMapper = mapper;
        }
    }
}
